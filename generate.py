#!/usr/bin/env python3
"""Generate cut files, previews and cut lists for every bed variant.

    python3 generate.py                      # defaults (3/4" ply, 64" nook)
    python3 generate.py --thickness 0.709    # measured 18 mm plywood
    python3 generate.py --set exit_width=18 --set nook_width=63.75
"""
import argparse
import dataclasses
import os

from bedgen.design import build_all
from bedgen.output import write_variant
from bedgen.params import Params


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--thickness", type=float, help="plywood thickness in inches")
    ap.add_argument("--set", action="append", default=[], metavar="NAME=VALUE",
                    help="override any field in bedgen/params.py")
    ap.add_argument("--out", default="output")
    ap.add_argument("--full", action="append", default=None, metavar="VARIANT",
                    help="variants that also get the STEP model and PDF drawings "
                         "(default: the side-exit beds; 'all' for every variant)")
    args = ap.parse_args()

    p = Params()
    if args.thickness:
        p.thickness = args.thickness
    fields = {f.name: f for f in dataclasses.fields(Params)}
    for kv in args.set:
        name, value = kv.split("=", 1)
        if name not in fields:
            ap.error(f"unknown parameter {name}")
        setattr(p, name, value if fields[name].type in (str, "str") else float(value))

    full = set(args.full or ["v1_side_exit", "v1b_side_exit_one_box", "v1c_side_exit_one_box_flush",
                         "v1d_side_exit_one_box_flowers", "v1e_side_exit_foot_box",
                         "v1f_side_exit_foot_box_trees",
                         "v1g_side_exit_foot_box_ferns"])
    sections = []
    for v in build_all(p):
        outdir = os.path.join(args.out, v.key)
        sections.append(write_variant(v, outdir, full="all" in full or v.key in full))
        print(f"wrote {outdir}")
    with open(os.path.join(args.out, "CUT_LIST.md"), "w") as f:
        f.write("# Cut lists\n\nAll sizes in inches, generated by `generate.py`.\n\n" + "\n".join(sections))


if __name__ == "__main__":
    main()
